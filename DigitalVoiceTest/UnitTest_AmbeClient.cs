    [Fact]
    public void Test_SendReceivePacket()
    {
        byte[] packet = [0x61, 0x00, 0x09, 0x01, 0x01, 0x31, 0xb0, 0x3b, 0x1b, 0x4f, 0xce, 0xa7, 0x00];
        Stopwatch stopwatch = new();
        stopwatch.Start();
        byte[] response = [];
        for (int i = 0; i < 5; i++)
        {
            response = client.SendReceivePacket(packet);
            output.WriteLine($"response length: {i} {response.Length}");
        }
        stopwatch.Stop();
        output.WriteLine($"Elapsed time: {stopwatch.Elapsed}");
        
        Assert.Equal(326, response.Length);
    }

    [Fact]
    public void Test_SendReceivePackets()
    {
        byte[] packet = [0x61, 0x00, 0x09, 0x01, 0x01, 0x31, 0xb0, 0x3b, 0x1b, 0x4f, 0xce, 0xa7, 0x00];
        Stopwatch stopwatch = new();
        stopwatch.Start();
        int n = 5;
        for (int i = 0; i < n; i++)
        {
            client.SendPacket(packet);
        }
        for (int i = 0; i < n; i++)
        {
            byte[] response = client.ReceivePacket();
            output.WriteLine($"response length: {i} {response.Length}");
            Assert.Equal(326, response.Length);
        }
        stopwatch.Stop();
        output.WriteLine($"Elapsed time: {stopwatch.Elapsed}");

    }

    [Fact]
    public void Test_Ambe_to_Pcm()
    {
        string packetFile = @"C:\Users\hgbir\VisualStudio_Source\repos\YSF\YsfClientTest\data\ambe_server_packets_20250725103921.bin";

        PacketRecorder? recorder = null;
        int channelPacketCount = 0;
        try
        {
            recorder = new(packetFile, FileMode.Open, FileAccess.Read);
            while (true)
            {
                byte[]? packet = recorder.ReadNextPacket();
                if (packet == null)
                    break;
                if (packet.Length == 13 && packet[0] == 0x61 && packet[3] == 0x01)
                {
                    channelPacketCount++;
                }
                client.SendPacket(packet);
                Thread.Sleep(10);
                byte[]? resp = client.ReceivePacket();
            }
        }
        finally
        {
            recorder?.Close();
            output.WriteLine($"channel packets read: {channelPacketCount}");
        }
